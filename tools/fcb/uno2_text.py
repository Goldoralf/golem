"""Le setup UnO2 en TEXTE — pour le coller dans le logiciel officiel (FCB UnO Control Center).

Sous Linux le rack compile et flashe la puce lui-même (uno2.py -> flash_uno2.py). Sous Windows et
macOS, décision (2026-10-02) : l'utilisateur colle ce texte dans Control Center, qui le
compile et l'envoie. Ce module produit ce texte.

⚠ UNE SEULE SOURCE. Le texte est DÉCOMPILÉ du même `uno2.Setup` que celui dont sort le binaire
(gen_uno2_syx.build), pas réécrit depuis le contrat : les deux sorties ne peuvent pas diverger. Et
`parse()` fait le chemin inverse — le texte relu doit redonner le binaire du rack AU BIT PRÈS
(tests/test_uno2_text.py, et `check()` avant toute copie).

Le langage, tel que Control Center l'a accepté le 2026-08-04 (docs/fcb/uno2/setup-v1.2.txt, corrigé
par le mainteneur dans l'éditeur) :
  · l'ORDRE des sections est imposé : listes (PRESETS, EFFECTS, TRIGGERS, SWEEPS), BANKS,
    REMOTE_CONTROL_CHANNEL puis CHANNEL, VAR, INIT_FCB, INIT_BANK, puis les contenus ;
  · variables préfixées `$`, déclarées `VAR $nom = valeur` ;
  · ⚠ Latin-1 SEULEMENT : les trois setups d'août ne compilaient pas à cause des traits `─` de leurs
    cadres de commentaires. On n'émet que de l'ASCII, et `check()` le vérifie.

    python3 tools/fcb/uno2_text.py            # le texte de la configuration courante (setlist au pied)
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import uno2

CHANNEL_NAME = "Golem"


class TextError(ValueError):
    pass


# ══ du bytecode au texte ══════════════════════════════════════════════════════════════════

def _names(setup):
    """index de switch -> nom d'élément, index de sweep -> nom, index de variable -> nom."""
    by_idx = {}
    for base, family in ((uno2.IDX_PRESET, setup.presets), (uno2.IDX_EFFECT, setup.effects),
                         (uno2.IDX_TRIGGER, setup.triggers)):
        for i, block in enumerate(family):
            by_idx[base + i] = block.name
    return by_idx, [s.name for s in setup.sweeps], [n for n, _ in setup.variables]


def _value(v, varnames):
    if 0x80 <= v <= 0xFF:
        return "$" + varnames[v & 0x7F]
    return str(v)


def decompile(code, setup, channel):
    """Une suite de bytecode -> une liste d'instructions du langage."""
    _, sweeps, varnames = _names(setup)
    out, i = [], 0
    while i < len(code):
        b = code[i]
        if b == uno2._ESC:
            op = code[i + 1]
            if op == uno2._OP_SETVAR:
                out.append("%s = %d" % (_value(code[i + 2], varnames), code[i + 3]))
                i += 4
            elif op == uno2._OP_PEDAL:
                out.append("Pedal %d = %s" % (code[i + 2] - 24, sweeps[code[i + 4]]))
                i += 5
            else:
                raise TextError("ordre 0x%02X sans équivalent texte connu" % op)
            continue
        high, ch = b & 0xF0, (b & 0x0F) + 1
        if ch != channel:
            raise TextError("canal %d dans le bytecode, %d attendu" % (ch, channel))
        if high == 0xC0:
            out.append("SendMidi %s ProgChange %s" % (CHANNEL_NAME, _value(code[i + 1], varnames)))
            i += 2
            continue
        kind = {0xB0: "CtrlChange", 0x90: "NoteOn", 0x80: "NoteOff"}.get(high)
        if not kind:
            raise TextError("message MIDI 0x%02X sans équivalent texte connu" % b)
        out.append("SendMidi %s %s %s %s" % (CHANNEL_NAME, kind, _value(code[i + 1], varnames),
                                             _value(code[i + 2], varnames)))
        i += 3
    return out


def _sweep_text(sweep, channel):
    c = sweep.content
    if len(c) != 7 or c[0] != uno2._ESC or c[1] != uno2._OP_SWEEP or c[2] != (0xB0 | (channel - 1)):
        raise TextError("sweep %s : forme inconnue" % sweep.name)
    if c[6] != uno2.SWEEP_LINEAR:
        raise TextError("sweep %s : style %d jamais écrit en texte" % (sweep.name, c[6]))
    return "SWEEP %s = SendMidi %s CtrlChange %d %d-%d" % (sweep.name, CHANNEL_NAME, c[3], c[4], c[5])


def _block(keyword, name, lines):
    return ["%s %s =" % (keyword, name), "{"] + ["  " + l for l in lines] + ["}"]


def render(setup, channel, title="GoleM", stamp=""):
    """Le texte complet d'un setup, dans l'ordre imposé par Control Center."""
    if setup.use_direct_bank or setup.no_updown_switches:
        raise TextError("use_direct_bank / no_updown_switches : jamais écrits en texte")
    by_idx, _, varnames = _names(setup)
    t = ["/* " + title, "   Generated by GoleM" + (" on " + stamp if stamp else "") + ".",
         "   Paste it in FCB UnO Control Center, compile, then send it to the chip.",
         "   Do not edit it there: GoleM writes it again from its own contract. */", ""]
    for keyword, family in (("PRESETS", setup.presets), ("EFFECTS", setup.effects),
                            ("TRIGGERS", setup.triggers), ("SWEEPS", setup.sweeps)):
        if family:
            t += ["%s =" % keyword, "{"] + ["  " + b.name for b in family] + ["}"]
    t += ["BANKS =", "{"]
    for bank in setup.banks:
        row = []
        for target in bank.switches:
            if target not in by_idx:
                raise TextError("bank %s : un switch sans élément ne s'écrit pas en texte" % bank.name)
            row.append(by_idx[target])
        t.append("  %s : %s" % (bank.name, " | ".join(row)))
    t.append("}")
    if setup.remote_control_channel:
        t.append("REMOTE_CONTROL_CHANNEL = %d" % setup.remote_control_channel)
    t.append("CHANNEL %s = %d" % (CHANNEL_NAME, channel))
    for name, value in setup.variables[1:]:            # l'index 0 est MidiChannel, intégrée
        t.append("VAR $%s = %d" % (name, value))
    if setup.init:
        t += ["INIT_FCB =", "{"] + ["  " + l for l in decompile(setup.init, setup, channel)] + ["}"]
    for bank in setup.banks:
        if bank.init:
            t += _block("INIT_BANK", bank.name, decompile(bank.init, setup, channel))
    for keyword_on, keyword_off, family in (("PRESET", "PRESET_RELEASE", setup.presets),
                                            ("EFFECT_ON ", "EFFECT_OFF", setup.effects),
                                            ("TRIGGER_CLICK", "TRIGGER_RELEASE", setup.triggers)):
        for b in family:
            if b.on:
                t += _block(keyword_on, b.name, decompile(b.on, setup, channel))
            if b.off:
                t += _block(keyword_off, b.name, decompile(b.off, setup, channel))
    for s in setup.sweeps:
        t.append(_sweep_text(s, channel))
    text = "\r\n".join(t) + "\r\n"
    return text


# ══ du texte au Setup (le chemin inverse, pour prouver l'équivalence) ═══════════════════

_TOK = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)


def parse(text, switch_count=10):
    """Relit un texte produit par render() et rend (Setup, canal). Ne sait lire QUE ce que
    render() écrit : c'est un vérificateur, pas un compilateur général du langage."""
    src = _TOK.sub("", text).replace("\r", "")
    lines = [l.strip() for l in src.split("\n") if l.strip()]
    setup = uno2.Setup(switch_count=switch_count)
    lists, channel, i = {}, None, 0
    pending_banks, pending = [], {}

    def take_block():
        nonlocal i
        if lines[i] != "{":
            raise TextError("« { » attendu ligne : %r" % lines[i])
        i += 1
        body = []
        while lines[i] != "}":
            body.append(lines[i])
            i += 1
        i += 1
        return body

    while i < len(lines):
        line = lines[i]
        m = re.fullmatch(r"(PRESETS|EFFECTS|TRIGGERS|SWEEPS|BANKS) =", line)
        if m:
            i += 1
            lists[m.group(1)] = take_block()
            continue
        m = re.fullmatch(r"REMOTE_CONTROL_CHANNEL = (\d+)", line)
        if m:
            setup.remote_control_channel = int(m.group(1)); i += 1; continue
        m = re.fullmatch(r"CHANNEL (\w+) = (\d+)", line)
        if m:
            channel = int(m.group(2)); i += 1; continue
        m = re.fullmatch(r"VAR \$(\w+) = (\d+)", line)
        if m:
            setup.add_variable(m.group(1), int(m.group(2))); i += 1; continue
        m = re.fullmatch(r"SWEEP (\w+) = SendMidi \w+ CtrlChange (\d+) (\d+)-(\d+)", line)
        if m:
            pending[("SWEEP", m.group(1))] = (int(m.group(2)), int(m.group(3)), int(m.group(4)))
            i += 1; continue
        m = re.fullmatch(r"(INIT_FCB|INIT_BANK|PRESET|PRESET_RELEASE|EFFECT_ON|EFFECT_OFF|TRIGGER_CLICK|TRIGGER_RELEASE)\s*(\w*) =", line)
        if m:
            i += 1
            pending[(m.group(1), m.group(2))] = take_block()
            continue
        raise TextError("ligne non comprise : %r" % line)
    if channel is None:
        raise TextError("aucun CHANNEL")
    varidx = {n: k for k, (n, _) in enumerate(setup.variables)}
    sweep_names = [s for s in lists.get("SWEEPS", [])]

    def val(tok):
        return uno2.var_ref(varidx[tok[1:]]) if tok.startswith("$") else int(tok)

    def compile_lines(body):
        code = []
        for l in body:
            m = re.fullmatch(r"SendMidi \w+ ProgChange (\S+)", l)
            if m:
                code += uno2.prog_change(channel, val(m.group(1))); continue
            m = re.fullmatch(r"SendMidi \w+ (CtrlChange|NoteOn|NoteOff) (\S+) (\S+)", l)
            if m:
                fn = {"CtrlChange": uno2.ctrl_change, "NoteOn": uno2.note_on, "NoteOff": uno2.note_off}[m.group(1)]
                code += fn(channel, val(m.group(2)), val(m.group(3))); continue
            m = re.fullmatch(r"Pedal (\d) = (\w+)", l)
            if m:
                code += uno2.assign_pedal(int(m.group(1)), sweep_names.index(m.group(2))); continue
            m = re.fullmatch(r"\$(\w+) = (\d+)", l)
            if m:
                code += uno2.set_var(varidx[m.group(1)], int(m.group(2))); continue
            raise TextError("instruction non comprise : %r" % l)
        return code

    for name in sweep_names:
        cc, lo, hi = pending[("SWEEP", name)]
        setup.add_sweep(uno2.Sweep(name, uno2.sweep_ctrl_change(channel, cc, lo, hi)))
    setup.init = compile_lines(pending.get(("INIT_FCB", ""), []))
    idx = {}
    for key, on_kw, off_kw, add in (("PRESETS", "PRESET", "PRESET_RELEASE", setup.add_preset),
                                    ("EFFECTS", "EFFECT_ON", "EFFECT_OFF", setup.add_effect),
                                    ("TRIGGERS", "TRIGGER_CLICK", "TRIGGER_RELEASE", setup.add_trigger)):
        for name in lists.get(key, []):
            idx[name] = add(uno2.Block(name, on=compile_lines(pending.get((on_kw, name), [])),
                                       off=compile_lines(pending.get((off_kw, name), []))))
    for row in lists.get("BANKS", []):
        name, _, rest = row.partition(":")
        name = name.strip()
        setup.add_bank(uno2.Bank(name, switches=[idx[s.strip()] for s in rest.split("|")],
                                 init=compile_lines(pending.get(("INIT_BANK", name), [])),
                                 switch_count=switch_count))
    return setup, channel


def check(text, binary):
    """Le texte est-il collable ET fidèle ? Rend la liste des problèmes (vide = bon)."""
    problems = []
    bad = sorted({c for c in text if ord(c) > 127})
    if bad:
        problems.append("non-ASCII characters (Control Center refuses non-Latin-1): " + "".join(bad))
    try:
        setup, _ = parse(text)
        if uno2.build_binary(setup) != binary:
            problems.append("the text does not compile back to the rack's binary")
    except (TextError, KeyError, IndexError, ValueError) as e:
        problems.append("the text cannot be read back: %s" % e)
    return problems


def current(stamp=""):
    """(texte, binaire, setup) de la configuration COURANTE — celle que le flash Linux enverrait."""
    import gen_uno2_syx as gen
    contract, device = gen.load()
    setup = gen.build(contract, device, looper_slots=gen.looper_slots_from_setlist(),
                      claim_slots=gen.claim_slots_from_setlist(contract))
    binary = uno2.build_binary(setup)
    text = render(setup, device["channel"], title="GoleM - setup for " + device["id"], stamp=stamp)
    return text, binary, setup, device


if __name__ == "__main__":
    text, binary, setup, device = current()
    problems = check(text, binary)
    sys.stdout.write(text)
    if problems:
        sys.stderr.write("✗ " + " ; ".join(problems) + "\n")
        sys.exit(1)
