"""Writes library/catalog/golem-fx-plugins.json: each golem-fx VST3 as REAPER names it, and its parameters' ranges.

REAPER writes a VST3 parameter NORMALIZED (0..1); golem's catalogue values are plain (dB, ms, %). To play golem-fx
blocks under REAPER (docs/golem-fx-reaper.md), golem_rig.lua needs, for each plugin, the name REAPER adds it by and
every parameter's plain range (all golem-fx ranges are linear: FloatRange::Linear) and option count. That comes from
golem-fx itself: each crate's plugin.rs (NAME, VST3_CLASS_ID) and `gfx-bench manifest` (visuals/data/manifest.json).
Each plugin also carries its DESCRIPTOR (visuals/data/descriptors.json, or a provisional one from the pedal faces):
the block sheet of docs/golem-fx-sheet.md.

  ./tools/sync-golem-fx-manifest.py                 # from ~/code/golem-fx (or --from)

The table is keyed by the VST3 class id as the Golem Engine's table writes it (hex of the 16 ASCII bytes), so the
two engines name the same plugin the same way.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "library" / "catalog" / "golem-fx-plugins.json"


def _provisional(crate, mparams, faces):
    """La face avant d'une pédale, faute du descripteur de golem-fx : ses commandes (sélecteurs, puis potards, puis
    interrupteurs), avec les bornes, défauts et libellés que dessine la pédale. Pas de groupes experts."""
    face = faces.get(crate) or {}
    by_id = {p["id"]: p for p in mparams}
    front, params = [], {}
    for p in [*(face.get("selectors") or []), *(face.get("knobs") or []), *(face.get("toggles") or [])]:
        m = by_id.get(p["id"], {})
        kind = p.get("kind") or m.get("kind") or "float"
        e = {"name": p.get("name") or m.get("name"), "kind": kind, "min": p.get("min", m.get("min")),
             "max": p.get("max", m.get("max")), "default": p.get("default", m.get("default")), "unit": None,
             "display": "lin", "exp": kind == "float", "structural": kind == "enum", "depends": None}
        if kind == "enum":
            e["options"] = p.get("options") or [str(i + 1) for i in range(int(m.get("options") or 2))]
        front.append(p["id"])
        params[p["id"]] = e
    return {"provisional": True, "front": front, "groups": [], "params": params, "presets": []}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--from", dest="src", default=os.path.expanduser("~/code/golem-fx"))
    a = ap.parse_args()
    src = Path(a.src)
    manifest = json.loads((src / "visuals" / "data" / "manifest.json").read_text(encoding="utf-8"))["effects"]
    # LE DESCRIPTEUR de chaque pédale (docs/golem-fx-sheet.md) : la face avant, les groupes experts et leurs interrupteurs
    # « Custom », les unités, les libellés — ce que la feuille du Designer montre. golem-fx l'exporte dans
    # visuals/data/descriptors.json ; tant qu'il n'y est pas, un descripteur PROVISOIRE est tiré des faces de pédale
    # (la face avant seule, sans groupes experts ni unités).
    dpath = src / "visuals" / "data" / "descriptors.json"
    descriptors = json.loads(dpath.read_text(encoding="utf-8")) if dpath.is_file() else {}
    descriptors = (descriptors.get("descriptors") or descriptors.get("pedals") or {}) if isinstance(descriptors, dict) else {}
    vdata = (src / "visuals" / "data" / "visuals-data.js").read_text(encoding="utf-8")
    faces = json.loads(vdata[vdata.index("=") + 1:].strip().rstrip(";")).get("gfx", {})
    plugins = {}
    for crate_dir in sorted(src.glob("gfx-*")):
        rs = crate_dir / "src" / "plugin.rs"
        if not rs.is_file() or crate_dir.name not in manifest:
            continue
        text = rs.read_text(encoding="utf-8")
        name = re.search(r'const NAME:\s*&\'static str\s*=\s*"([^"]+)"', text)
        cid = re.search(r'VST3_CLASS_ID:\s*\[u8;\s*16\]\s*=\s*\*b"([^"]{16})"', text)
        if not (name and cid):
            continue
        params = {}
        for p in manifest[crate_dir.name]:
            e = {"kind": p.get("kind", "float"), "min": p.get("min", 0), "max": p.get("max", 1)}
            if e["kind"] == "enum":
                e["n"] = int(p.get("options") or (p.get("max", 1) - p.get("min", 0) + 1))
            params[p["name"]] = e
        plugins[cid.group(1).encode().hex().upper()] = {
            "crate": crate_dir.name, "name": name.group(1),
            # le nom sous lequel REAPER l'ajoute (TrackFX_AddByName) : « VST3: <NAME> (<éditeur>) »
            "reaper": f"VST3: {name.group(1)} (GoleM)", "params": params,
            "descriptor": descriptors.get(crate_dir.name) or _provisional(crate_dir.name, manifest[crate_dir.name], faces)}
    commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    doc = {"_comment": "Generated by tools/sync-golem-fx-manifest.py from golem-fx (plugin.rs + gfx-bench manifest). "
                       "Do not edit. Keyed by VST3 class id (hex), as in effects-golem-engine.json. Ranges are plain "
                       "and linear; `n` = option count of an enum. Read by golem_rig.lua (golem-fx under REAPER).",
           "golem_fx_commit": commit, "plugins": plugins}
    OUT.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(plugins)} golem-fx plugins from golem-fx {commit[:10]} -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
