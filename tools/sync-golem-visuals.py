"""Brings golem-fx's visuals (glyphs, pedal and pedalboard renderers) into the app, from a golem-fx checkout.

golem-fx (separate repository, GPL-3.0) draws every golem block: one SVG glyph per catalogue type, and the pedals and
the pedalboard of the Designer's pedal view (docs/designer-glyphs-pedals.md). The app does not read another
repository at run time: this tool copies what it needs and records the commit it came from.

  ./tools/sync-golem-visuals.py                 # from ~/code/golem-fx (or --from)
  ./tools/sync-golem-visuals.py --fonts         # also (re)download the pedal fonts (OFL) for offline use

Writes:
  app/glyphs.js                                 GLYPHS = {type: {svg, uni, label}} (svg: inner markup on a 24 grid)
  app/vendor/golem-visuals/golem-pedals.js      the renderers, as golem-fx ships them (plain scripts)
  app/vendor/golem-visuals/golem-stage.js
  app/vendor/golem-visuals/visuals-data.js
  app/vendor/golem-visuals/SOURCE.json          golem-fx commit, date
  app/vendor/golem-visuals/fonts/*.woff2, OFL-*.txt + fonts.css   (--fonts)
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "app" / "vendor" / "golem-visuals"
FONTS = {"Saira Semi Condensed": "400;600;700", "Shrikhand": "400", "Big Shoulders Display": "600;800", "Pirata One": "400"}


def _fonts():
    """Les fichiers woff2 (sous-ensemble latin) des trois polices, et la feuille @font-face qui les nomme."""
    fam = "&".join("family=" + n.replace(" ", "+") + (":wght@" + w if ";" in w or w != "400" else "") for n, w in FONTS.items())
    req = urllib.request.Request("https://fonts.googleapis.com/css2?" + fam + "&display=swap",
                                 headers={"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/120 Safari/537.36"})
    css = urllib.request.urlopen(req, timeout=30).read().decode()
    out, n = [], 0
    (DEST / "fonts").mkdir(parents=True, exist_ok=True)
    # un bloc par sous-ensemble : on ne garde que « latin » (le rack n'écrit rien d'autre sur une pédale)
    for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css):
        if m.group(1) != "latin":
            continue
        face = m.group(2)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", face).group(1)
        fam_n = re.search(r"font-family:\s*'([^']+)'", face).group(1)
        wt = re.search(r"font-weight:\s*(\d+)", face).group(1)
        fn = f"{fam_n.lower().replace(' ', '-')}-{wt}.woff2"
        (DEST / "fonts" / fn).write_bytes(urllib.request.urlopen(url, timeout=30).read())
        out.append(face.replace(url, "fonts/" + fn))
        n += 1
    # la licence OFL de chaque famille, à côté de ses fichiers (l'OFL exige qu'elle voyage avec la police)
    for slug in (fam.replace(" ", "").lower() for fam in FONTS):          # le dossier de Google Fonts : le nom sans espaces
        txt = urllib.request.urlopen(f"https://raw.githubusercontent.com/google/fonts/main/ofl/{slug}/OFL.txt", timeout=30).read()
        (DEST / "fonts" / f"OFL-{slug}.txt").write_bytes(txt)
    (DEST / "fonts.css").write_text("/* Generated by tools/sync-golem-visuals.py — OFL fonts of golem-fx's pedals, latin subset */\n"
                                    + "\n".join(out) + "\n", encoding="utf-8")
    return n


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--from", dest="src", default=os.path.expanduser("~/code/golem-fx"))
    ap.add_argument("--fonts", action="store_true", help="download the pedal fonts (needs the network)")
    a = ap.parse_args()
    vis = Path(a.src) / "visuals"
    if not (vis / "js" / "golem-pedals.js").is_file():
        raise SystemExit(f"no golem-fx visuals in {vis}")
    DEST.mkdir(parents=True, exist_ok=True)
    for rel, name in (("js/golem-pedals.js", "golem-pedals.js"), ("js/golem-stage.js", "golem-stage.js"),
                      ("data/visuals-data.js", "visuals-data.js")):
        (DEST / name).write_bytes((vis / rel).read_bytes())
    g = json.loads((vis / "data" / "glyphs.json").read_text(encoding="utf-8"))
    g = g.get("glyphs", g)
    glyphs = {t: {"svg": v["svg"], "uni": v.get("uni") or "", "label": v.get("label") or t} for t, v in sorted(g.items())}
    (ROOT / "app" / "glyphs.js").write_text(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n"
        "// Generated by tools/sync-golem-visuals.py from golem-fx (visuals/data/glyphs.json). Do not edit.\n"
        "// One glyph per catalogue type: inner SVG on a 24 x 24 grid, stroked in currentColor; `uni` = the former\n"
        "// Unicode glyph, kept as a text fallback (docs/designer-glyphs-pedals.md).\n"
        "export const GLYPHS = " + json.dumps(glyphs, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    commit = subprocess.run(["git", "-C", a.src, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    (DEST / "SOURCE.json").write_text(json.dumps({"repo": "golem-fx", "path": "visuals/", "commit": commit,
                                                  "synced": time.strftime("%Y-%m-%d")}, indent=1) + "\n", encoding="utf-8")
    nf = _fonts() if a.fonts else 0
    print(f"{len(glyphs)} glyphs, renderers from golem-fx {commit[:10]}" + (f", {nf} font files" if nf else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
